"""Write reports/profiling.md: descriptive facts about the rebuilt catalog.

Facts only; no interpretation. Usage (from the repo root, after src.download):
    python -m src.profiling
"""
import hashlib
from pathlib import Path

import numpy as np
import pandas as pd

from src import clean

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "reports" / "profiling.md"
PLAIN_COLS = {"year", "month", "eventID", "date"}


def fmt(col: str, v) -> str:
    v = v.item() if hasattr(v, "item") else v
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return ""
    if isinstance(v, bool) or col in PLAIN_COLS:
        return str(v)
    if isinstance(v, (int, np.integer)):
        return f"{v:,}"
    if isinstance(v, float):
        return f"{v:,.0f}" if v.is_integer() else f"{v:,.1f}"
    return str(v)


def md_table(df: pd.DataFrame, index: bool = True) -> str:
    d = df.reset_index() if index else df
    cols = [str(c) for c in d.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in d.itertuples(index=False):
        lines.append("| " + " | ".join(fmt(c, v) for c, v in zip(cols, row)) + " |")
    return "\n".join(lines)


def max_curvature(mags: pd.Series) -> float | None:
    """Maximum-curvature completeness estimate: the most populated 0.1 magnitude bin."""
    m = mags.dropna()
    if m.empty:
        return None
    return float(m.round(1).value_counts().idxmax())


def main() -> None:
    cat = clean.read_catalog()
    days = clean.read_days()
    cat["in_box"] = clean.in_box(cat)
    box = cat[cat.in_box]
    ok = clean.valid_days(days)
    years = sorted(box.year.unique())
    out = []
    w = out.append

    w("# Profiling report")
    w("")
    w("Generated by `src/profiling.py` from the rebuilt `data/raw/katalog_gempa_v2.tsv` "
      f"(SHA-256 `{hashlib.sha256(clean.CATALOG.read_bytes()).hexdigest()}`). Descriptive facts only.")
    w("")
    w("Rates are \"per year of valid data\": events ÷ `ok` days × 365.25 (the method that reproduces the brief; see `reports/number_check.md`). "
      "Years are assigned by the event's UTC date.")
    w("")

    w("## 1. Schema and formats")
    w("")
    fill = pd.DataFrame({"non-empty (all events)": cat.drop(columns=["datetime_utc", "date", "year", "month", "in_box"])
                         .replace("", np.nan).notna().sum()})
    w(md_table(fill.head(11).rename_axis("column")))
    w("")
    w(f"- {len(cat):,} events, 37 columns; the 26 focal-mechanism columns (`datetimeFM` … `misfit`) are filled for at most {int(cat['datetimeFM'].ne('').sum()):,} events.")
    w(f"- `eventID` duplicates: {int(cat.eventID.duplicated().sum())}.")
    n_whole = int((~cat.datetime.str.contains(r"\.", regex=True)).sum())
    w(f"- `datetime`: {n_whole} timestamps have no fractional seconds; the rest carry microseconds (mixed formats; parsed as ISO 8601).")
    w(f"- `mag_type` labels (all events): " + ", ".join(f"`{k}` {v:,}" for k, v in cat.mag_type.value_counts().items())
      + f"; blank {int(cat.mag_type.isna().sum()):,}.")
    w("")

    w("## 2. Analysis box and coverage")
    w("")
    b = clean.BOX
    w(f"Box: latitude {b['lat_min']} … {b['lat_max']}, longitude {b['lon_min']} … {b['lon_max']} (inclusive). "
      f"{int(cat.in_box.sum()):,} events inside, {int((~cat.in_box).sum()):,} outside.")
    w("")
    broken = days[days.status == "broken"].groupby("year").size()
    cov = pd.DataFrame({
        "events (all)": cat.groupby("year").size(),
        "events (box)": box.groupby("year").size(),
        "ok days": ok, "broken days": broken,
    }).fillna(0).astype(int)
    cov["box events per ok day"] = (cov["events (box)"] / cov["ok days"]).round(1)
    w(md_table(cov.rename_axis("year")))
    w("")
    first, last = days.date.min(), days.date.max()
    w(f"Archive days run {first} → {last}; 2008 and 2026 are partial years. Events (box) dated on a `broken` day: "
      f"{int(box.date.isin(set(days[days.status == 'broken'].date)).sum())}.")
    w("")

    w("## 3. Rates per year, by magnitude class (box)")
    w("")
    rows = []
    for y in years:
        sub = box[box.year == y]
        r = lambda s: len(s) / ok.get(y, np.nan) * clean.DAYS_PER_YEAR
        rows.append({"year": y, "events": len(sub), "rate (all)": r(sub), "rate (< M4)": r(sub[sub.magnitude < 4]),
                     "rate (M4+)": r(sub[sub.magnitude >= 4]), "rate (M5+)": r(sub[sub.magnitude >= 5]),
                     "no magnitude": int(sub.magnitude.isna().sum())})
    w(md_table(pd.DataFrame(rows), index=False))
    w("")

    w("## 4. Magnitude type mix per year (box, share of events with a magnitude)")
    w("")
    mix = pd.crosstab(box.year, box.mag_type, normalize="index").mul(100).round(1)
    mix = mix[mix.sum().sort_values(ascending=False).index]
    w(md_table(mix.map(lambda v: f"{v:.1f}%")))
    w("")

    w("## 5. Completeness (maximum curvature, 0.1 bins, box)")
    w("")
    mc = pd.DataFrame([{"year": y, "max-curvature bin": max_curvature(box[box.year == y].magnitude)} for y in years])
    mc["+0.2 correction"] = mc["max-curvature bin"] + 0.2
    w(md_table(mc, index=False))
    w("")

    w("## 6. Numeric columns (box)")
    w("")
    num = box[["magnitude", "depth", "phasecount", "azimuth_gap"]]
    desc = pd.DataFrame({"missing": num.isna().sum(), "zero": (num == 0).sum(), "min": num.min(), "median": num.median(),
                         "p99": num.quantile(0.99), "max": num.max()}).rename_axis("column")
    w(md_table(desc))
    w("")
    deep = box[box.depth > 700][["eventID", "date", "latitude", "longitude", "depth", "magnitude", "location"]]
    w(f"Events with `depth` > 700 (units not documented upstream): {len(deep)}.")
    if len(deep):
        w("")
        w(md_table(deep.sort_values("depth", ascending=False).head(10), index=False))
    w("")

    w("## 7. Collection context (from the author's README / MANIFEST, not verifiable in the file)")
    w("")
    w("- Source: BMKG RepoGempa *preliminary* catalog; recent events may be revised.")
    w("- Field meanings, units and methods are BMKG's to define; the repository documents structure only.")
    w("- `broken` days are collection gaps, not zero seismicity.")
    w("- The catalog is not clipped to Indonesia; the analysis box still includes border areas.")
    w("")

    w("## 8. Reconciliation with announced totals")
    w("")
    y24_all, y24_box = int((cat.year == 2024).sum()), int((box.year == 2024).sum())
    w(f"BMKG's announced 2024 total, as cited in the brief: 29,869 (not verified here). This catalog: {y24_all:,} events dated 2024 "
      f"(any location), {y24_box:,} inside the box. Difference to the announced figure: {29869 - y24_all:,} (all) / {29869 - y24_box:,} (box). "
      "No other announced yearly totals were supplied.")
    w("")

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(out))
    print(f"wrote {REPORT.relative_to(ROOT)} ({len(out)} lines)")


if __name__ == "__main__":
    main()
